// 課程規劃 prompt：把 /tna 的精準數據交給 LLM，要它產出課程規劃。
// 數字來自我們的計算，LLM 不重算、只解讀與規劃。

export function buildCoursePrompt(tna: unknown): { system: string; user: string } {
  const system = [
    '你是一位資深企業教育訓練顧問，專長是把「訓練需求調查數據」轉成可執行的內訓課程規劃。',
    '你會拿到一份已經由系統精準計算好的需求分析數據（JSON），包含：回收概況、痛點年工時排序、',
    '數位能力分級分佈、建議分班（職務群×能力）、可受訓時段。',
    '',
    '重要規則：',
    '1. 數據裡的數字（年工時、人數、分級）是精準計算結果，直接引用，不要自己重算或編造新數字。',
    '2. 用繁體中文，語氣專業但好懂，對象是要看這份規劃來決定開課的主管。',
    '3. 課程規劃要具體到「開幾堂、每堂主題、每堂重點、對應到哪個痛點或能力落差」。',
    '4. 若某類資料為空（例如受訓時段沒人填），就說明資料不足、給出建議做法，不要硬掰。',
  ].join('\n');

  const user = [
    '以下是這個專案的訓練需求分析數據（TNA）：',
    '```json',
    JSON.stringify(tna, null, 2),
    '```',
    '',
    '請據此產出一份課程規劃，包含這幾個部分：',
    '',
    '## 一、需求總覽',
    '用 3-5 句話總結這個組織最該優先解決什麼、為什麼（引用關鍵年工時數字）。',
    '',
    '## 二、痛點解讀',
    '挑出年工時最高的前 3-5 個痛點，各用 2-3 句說明它代表的問題與可切入的改善方向',
    '（例如：可用 AI/工具自動化、流程簡化、範本化）。',
    '',
    '## 三、能力落差',
    '根據數位能力分級分佈與最弱面向，說明整體數位素養落在哪、哪個職務群最需要補強。',
    '',
    '## 四、課程規劃',
    '依「建議分班」提出每一班的課程安排。每班請給：',
    '- 班別名稱與對象（職務群 × 能力分級、人數）',
    '- 建議堂數與總時數',
    '- 每一堂的主題、重點內容、對應解決的痛點或能力落差',
    '- 這班訓後應具備的能力（KSA：知識/技能/態度）',
    '',
    '## 五、驗收建議',
    '給出可衡量的訓後成效指標（可對應 Kirkpatrick L2 學習、L3 行為）。',
  ].join('\n');

  return { system, user };
}
